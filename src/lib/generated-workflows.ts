import { stringify } from "yaml";
import { z } from "zod";
import { repositoryEntry, type Config } from "./config.ts";

export const STANDARD_CALLERS = {
  approve: "client-approve.yml",
  "policy-check": "client-policy-check.yml",
  merge: "client-merge.yml",
  release: "client-release-publish.yml",
  "release-pr": "client-release-prepare.yml",
} as const;
export type Caller = keyof typeof STANDARD_CALLERS;
export const callerPath = (caller: Caller): string => `.github/workflows/csm-ci-${caller}.yml`;
export const ReleasedRevision = z.strictObject({ version: z.string().regex(/^v(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$/u), sha: z.string().regex(/^[a-f0-9]{40}$/u) });
export type ReleasedRevision = z.infer<typeof ReleasedRevision>;
export type GeneratedWorkflows = { release: ReleasedRevision; files: Readonly<Record<string, string>> };
// The first-line header is the only ownership signal: header files no longer desired are deleted, others are never touched.
export const GENERATED_HEADER = "# Generated by csm-ci from ";
export const hasGeneratedHeader = (text: string): boolean => text.startsWith(GENERATED_HEADER);
export const isWorkflowFileName = (name: string): boolean => name.endsWith(".yml") || name.endsWith(".yaml");

export function selectedCallers(config: Config, repository: string): Caller[] {
  const entry = repositoryEntry(config, repository);
  if (!entry) throw new Error(`repository ${repository} is not configured`);
  const selected: Caller[] = [];
  for (const op of ["approve", "policy-check", "merge", "release"] as const) if (entry.ops.includes(op)) selected.push(op);
  if (entry.ops.includes("securefix") && config.securefix?.routes.some((route) => route.name === "release-pr")) selected.push("release-pr");
  return selected;
}

export function generateWorkflows(config: Config, repository: string, defaultBranch: string, release: ReleasedRevision): Record<string, string> {
  ReleasedRevision.parse(release);
  const entry = repositoryEntry(config, repository);
  return Object.fromEntries(selectedCallers(config, repository).map((caller) => {
    const prepare = caller === "release-pr";
    const files = entry?.release_prepare?.version_files;
    const events = caller === "approve"
      ? { pull_request_target: { types: ["opened", "synchronize", "reopened", "ready_for_review"] }, issue_comment: { types: ["created"] } }
      : caller === "policy-check" ? { pull_request_target: { types: ["opened", "synchronize", "reopened", "ready_for_review", "edited"] } }
      : caller === "merge" ? { issue_comment: { types: ["created"] } }
      : caller === "release" ? { pull_request: { types: ["closed"] } }
      : { push: { branches: [defaultBranch] }, workflow_dispatch: { inputs: { version: { description: "Optional semantic version without a v prefix.", type: "string", required: false, default: "" } } } };
    const job = {
      ...(prepare ? { if: "github.event_name == 'workflow_dispatch' || (!startsWith(github.event.head_commit.message, 'chore(release): v') && !startsWith(github.event.head_commit.message, 'release-pr: chore(release): v'))" } : {}),
      uses: `civitaspo/csm-ci-actions/.github/workflows/${STANDARD_CALLERS[caller]}@${release.sha}`,
      permissions: prepare ? { contents: "read" } : {},
      ...(prepare ? { with: { version: "${{ inputs.version || '' }}", ...(files ? { "version-files": JSON.stringify(files) } : {}) } } : {}),
      secrets: { CSM_CI_CLIENT_APP_PRIVATE_KEY: "${{ secrets.CSM_CI_CLIENT_APP_PRIVATE_KEY }}" },
    };
    const body = stringify({ name: `csm-ci-${caller}`, on: events, permissions: {}, jobs: { [caller]: job } }, { lineWidth: 0 });
    // Pin comments match what pinact-style autofix adds, so client autofix leaves generated bytes unchanged.
    const pinned = body.replace(`@${release.sha}\n`, `@${release.sha} # ${release.version}\n`);
    // Client callers intentionally use these triggers and never cancel requests; jactionlint in linted repositories must accept them.
    const lint = caller === "release" || caller === "release-pr" ? "concurrency-limits" : "concurrency-limits,dangerous-triggers";
    return [callerPath(caller), `${GENERATED_HEADER}${release.version} (${release.sha}).\n${pinned.replace("\non:\n", `\n# jactionlint ignore=${lint}\non:\n`)}`];
  }));
}
